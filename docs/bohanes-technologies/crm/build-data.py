"""Generate public CRM browser assets from the one reviewed source of truth.
Run from any directory: python3 path/to/crm/build-data.py
Do not add private CRM exports or internal notes to this public repository.
"""
import json
from pathlib import Path

root = Path(__file__).resolve().parent
rows = json.loads((root / 'data/verified-records.json').read_text())
assert len(rows) == 36 and len({x['name'] for x in rows}) == 36
for row in rows:
    assert (row.get('company') or row['name'] == 'Karlovy Vary') and row.get('website') and row.get('sources')
    assert row.get('historicalLand') in ('Čechy', 'Morava', 'Slezsko')
    assert not row.get('ico') or (len(row['ico']) == 8 and row['ico'].isdigit())
    assert all(c.get('name') and c.get('role') and c.get('note') for c in row.get('contacts', []))
payload = json.dumps(rows, ensure_ascii=False, indent=2) + '\n'
for folder in ('app', 'site'):
    (root / folder / 'crm-data.json').write_text(payload)
    (root / folder / 'crm-data.js').write_text('// Generated by ../build-data.py; public facts only.\nwindow.BOHANES_CRM_VERIFIED=' + payload.rstrip() + ';\n')
print(f'{len(rows)} public records generated for app/ and site/.')
